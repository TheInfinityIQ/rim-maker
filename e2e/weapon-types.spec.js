import { test, expect } from '@playwright/test';
import JSZip from 'jszip';
import fs from 'node:fs/promises';
test('creates, edits and exports melee and grenade weapons together', async ({ page }, info) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('#/weapon');
  await page.getByRole('button', { name: 'Add your first weapon' }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('combobox', { name: 'Weapon type', exact: true }).click();
  await page.getByRole('option', { name: 'Melee weapon', exact: true }).click();
  await dialog.getByRole('button', { name: 'Add weapons', exact: true }).click();
  await page.locator('#weaponName').fill('Frontier longsword');
  await page.getByRole('tab', { name: 'Combat', exact: true }).click();
  await expect(page.getByText('Melee weapon', { exact: true }).last()).toBeVisible();
  await expect(page.getByRole('region', { name: 'Weapon preview', exact: true })).toHaveCount(0);
  await page.getByLabel('Damage amount', { exact: true }).nth(1).fill('30');
  await page.getByRole('spinbutton', { name: 'Melee tool 2 armour penetration' }).fill('0.4');
  await page.getByRole('spinbutton', { name: 'Melee tool 2 armour penetration' }).press('Tab');
  await page.getByRole('tab', { name: 'Crafting', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: 'Choose material when crafting' })).toBeChecked();
  await page.getByRole('button', { name: 'Add weapons', exact: true }).click();
  await dialog.getByRole('combobox', { name: 'Weapon type', exact: true }).click();
  await page.getByRole('option', { name: 'Grenade', exact: true }).click();
  await dialog.getByRole('button', { name: 'Add weapons', exact: true }).click();
  await page.locator('#weaponName').fill('Frontier frag grenade');
  await page.getByRole('tab', { name: 'Combat', exact: true }).click();
  await expect(page.locator('#weaponRange')).toHaveValue('12.9');
  await page.getByRole('button', { name: 'Bullet', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Projectile behavior', exact: true })).toContainText('Frag grenade');
  await expect(page.locator('#bulletExplosionDelay')).toHaveValue('100');
  const downloading = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export mod', exact: true }).click();
  const download = await downloading, file = info.outputPath('mixed-weapons.zip'); await download.saveAs(file);
  const zip = await JSZip.loadAsync(await fs.readFile(file));
  const xml = await zip.file('TestMod/Defs/ThingDefs/TestModWeapons_Ranged.xml').async('string');
  expect(xml).toContain('ParentName="BaseMeleeWeapon_Sharp_Quality"');
  expect(xml).toContain('ParentName="BaseMakeableGrenade"');
  expect(xml).toContain('<power>30</power>'); expect(xml).toContain('<armorPenetration>0.4</armorPenetration>');
  expect(xml).toContain('<explosionDelay>100</explosionDelay>');
  expect(xml).toContain('<verbClass>Verb_LaunchProjectile</verbClass>');
  await page.getByRole('button', { name: /Frontier longsword/ }).click();
  await page.getByRole('tab', { name: 'Combat', exact: true }).click();
  await expect(page.getByLabel('Damage amount', { exact: true }).nth(1)).toHaveValue('30');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.weapon-editor').screenshot({ path: info.outputPath('melee-mobile.png') });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  expect(errors).toEqual([]);
});

test('equipment guide separates supported templates from special weapons and explains apparel', async ({ page }) => {
  await page.goto('#/reference');
  await expect(page.getByRole('heading', { name: 'Weapons & wearables' })).toBeVisible();
  await page.getByRole('textbox', { name: 'Search equipment definitions' }).fill('Verb_ShootBeam');
  await expect(page.locator('tbody')).toContainText('Gun_BeamGraser');
  await page.getByRole('textbox', { name: 'Search equipment definitions' }).fill('');
  await page.getByRole('tab', { name: 'Armour & wearables' }).click();
  await expect(page.getByText('Armour and wearables are not yet creatable', { exact: false })).toBeVisible();
  await page.getByRole('textbox', { name: 'Search equipment definitions' }).fill('FlakVest');
  await expect(page.locator('tbody')).toContainText('Middle');
  await expect(page.locator('tbody')).toContainText('Torso');
});
